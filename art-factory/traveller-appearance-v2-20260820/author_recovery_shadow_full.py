def write_high_risk_previews(assets: Sequence[dict[str, object]]) -> list[Path]:
    outputs: list[Path] = []
    root = PREVIEW_ROOT / "high-risk-contacts"
    root.mkdir(parents=True, exist_ok=True)
    by_id = {str(asset["id"]): asset for asset in assets}
    for asset_id, box in HIGH_RISK_CROPS.items():
        asset = by_id[asset_id]
        with Image.open(public_asset_path(REPO_ROOT, asset["baseRoute"])) as opened:
            base = opened.convert("RGBA")
        with Image.open(safe_relative(ROOT, asset["matteFile"])) as opened:
            matte = opened.convert("L")
        crop = overlay(base, matte).crop(box)
        crop = crop.resize((crop.width * 3, crop.height * 3), Image.Resampling.NEAREST)
        output = root / f"{asset_id.replace(':', '--')}-matte-3x.png"
        crop.save(output, "PNG", optimize=True)
        outputs.append(output)
    return outputs


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_qa(
    assets: Sequence[dict[str, object]],
    measured: Sequence[Validation],
    validation: Validation,
    previews: Sequence[Path],
) -> tuple[Path, Path]:
    QA_ROOT.mkdir(parents=True, exist_ok=True)
    rows = []
    for asset, result in zip(assets, measured):
        mask_path = safe_relative(ROOT, asset["maskFile"])
        matte_path = safe_relative(ROOT, asset["matteFile"])
        rows.append({
            "id": asset["id"],
            "passed": result.passed,
            "errors": list(result.errors),
            "facts": result.facts,
            "maskSha256": sha256(mask_path),
            "matteSha256": sha256(matte_path),
        })
    payload = {
        "schema": "satoru.traveller-appearance.factory-batch-qa/1",
        "batch": BATCH,
        "scope": {"capabilities": sorted(CAPABILITIES), "required": 20, "counts": EXPECTED_COUNTS},
        "machineGate": {"passed": validation.passed, "passedAssets": validation.facts.get("passed"), "requiredAssets": validation.facts.get("required")},
        "ownershipContract": "explicit-positive-negative-geometry; no colour-based actor exclusion",
        "publicArtWrites": False,
        "manualVisualReview": "completed-native-full-and-high-risk-zoom-2026-08-20",
        "assets": rows,
        "previews": [str(path.relative_to(ROOT)) for path in previews],
    }
    json_path = QA_ROOT / "qa-report.json"
    md_path = QA_ROOT / "qa-report.md"
    json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = [
        f"# {BATCH}", "",
        f"- Machine gate: **{'PASS' if validation.passed else 'FAIL'}** ({validation.facts.get('passed')}/{validation.facts.get('required')})",
        "- Public art writes: **none**",
        "- Ownership: explicit positive/negative silhouette geometry; colour never selects actor ownership.",
        "- Manual visual review: **PASS — native full sheets and high-risk 3× contact crops**", "",
        "| Asset | Gate | Traveller px | Semantic px |", "|---|---:|---:|---:|",
    ]
    for row in rows:
        facts = row["facts"]
        lines.append(f"| `{row['id']}` | {'PASS' if row['passed'] else 'FAIL'} | {facts.get('travellerPixels')} | {facts.get('semanticPixels')} |")
    md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return json_path, md_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write exactly the twenty batch-owned masks and mattes")
    parser.add_argument("--overwrite-owned", action="store_true", help="replace only this batch's twenty mask/matte pairs")
    args = parser.parse_args()

    inventory = load_inventory()
    assets = [asset for asset in inventory["assets"] if asset["capability"] in CAPABILITIES]
    counts = {capability: sum(asset["capability"] == capability for asset in assets) for capability in CAPABILITIES}
    by_id = {str(asset["id"]): asset for asset in assets}
    if len(assets) != 20 or counts != EXPECTED_COUNTS or set(by_id) != TARGET_IDS:
        raise SystemExit(f"Recovery/Shadow inventory drift: assets={len(assets)} counts={counts}")
    assets = [by_id[asset_id] for asset_id in sorted(TARGET_IDS)]

    authored: list[tuple[dict[str, object], Image.Image, Image.Image]] = []
    for asset in assets:
        with Image.open(public_asset_path(REPO_ROOT, asset["baseRoute"])) as opened:
            opened.load()
            semantic, matte = author(opened.convert("RGBA"), FRAME_CONFIGS[str(asset["id"])])
        authored.append((asset, semantic, matte))
    print(f"preflight: PASS ({len(authored)} masks + {len(authored)} mattes; exactScope=20)")
    if not args.write:
        print("factoryWrites: false; publicArtWrites: false")
        return

    for asset, semantic, matte in authored:
        write_png(safe_relative(ROOT, asset["maskFile"]), semantic, overwrite_owned=args.overwrite_owned)
        write_png(safe_relative(ROOT, asset["matteFile"]), matte, overwrite_owned=args.overwrite_owned)

    measured = [validate_semantic_mask(asset) for asset in assets]
    validation = validate_mask_set(assets, results=measured)
    result_map = {str(result.facts["asset"]): result for result in measured}
    previews = write_contact_sheets(assets, result_map)
    previews.extend(write_high_risk_previews(assets))
    reports = write_qa(assets, measured, validation, previews)
    print(f"validation: {'PASS' if validation.passed else 'FAIL'} ({validation.facts.get('passed')}/{validation.facts.get('required')})")
    for result in measured:
        facts = result.facts
        print(f"{facts.get('asset')}: {'PASS' if result.passed else 'FAIL'} traveller={facts.get('travellerPixels')} semantic={facts.get('semanticPixels')} channels={facts.get('channelPixels')}")
        for error in result.errors:
            print(f"  ERROR: {error}")
    for preview in previews:
        print(f"preview: {preview.relative_to(ROOT)}")
    for report in reports:
        print(f"qa: {report.relative_to(ROOT)}")
    print("publicArtWrites: false")
    if not validation.passed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
