def parse_explicit_rows(encoded: str) -> tuple[tuple[int, int, int], ...]:
    spans: list[tuple[int, int, int]] = []
    for line in encoded.splitlines():
        if not line:
            continue
        y_text, runs_text = line.split(":", 1)
        y = int(y_text)
        for run in runs_text.split(","):
            left_text, right_text = run.split("-", 1)
            spans.append((y, int(left_text), int(right_text)))
    return tuple(spans)


