def rgb_to_hsv(rgb: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    normalized = rgb.astype(np.float32) / 255.0
    maximum = normalized.max(axis=2)
    minimum = normalized.min(axis=2)
    delta = maximum - minimum
    hue = np.zeros_like(maximum)
    nonzero = delta > 1e-6
    red, green, blue = normalized[..., 0], normalized[..., 1], normalized[..., 2]
    selected = nonzero & (maximum == red)
    hue[selected] = ((green[selected] - blue[selected]) / delta[selected]) % 6
    selected = nonzero & (maximum == green)
    hue[selected] = ((blue[selected] - red[selected]) / delta[selected]) + 2
    selected = nonzero & (maximum == blue)
    hue[selected] = ((red[selected] - green[selected]) / delta[selected]) + 4
    return hue / 6.0, np.where(maximum > 1e-6, delta / np.maximum(maximum, 1e-6), 0), maximum


def polygons(size: tuple[int, int], values: Iterable[Iterable[tuple[int, int]]]) -> np.ndarray:
    image = Image.new("L", size, 0)
    draw = ImageDraw.Draw(image)
    for points in values:
        draw.polygon(list(points), fill=255)
    return np.asarray(image, dtype=np.uint8) > 0


def rectangles(size: tuple[int, int], values: Iterable[tuple[int, int, int, int]]) -> np.ndarray:
    image = Image.new("L", size, 0)
    draw = ImageDraw.Draw(image)
    for box in values:
        draw.rectangle(box, fill=255)
    return np.asarray(image, dtype=np.uint8) > 0


def connected_components(mask: np.ndarray) -> list[np.ndarray]:
    """Return 8-connected material components as flattened indexes."""
    remaining = mask.copy()
    height, width = mask.shape
    found: list[np.ndarray] = []
    while np.any(remaining):
        start_y, start_x = np.argwhere(remaining)[0]
        remaining[start_y, start_x] = False
        stack = [(int(start_y), int(start_x))]
        indexes: list[int] = []
        while stack:
            y, x = stack.pop()
            indexes.append(y * width + x)
            for delta_y in (-1, 0, 1):
                for delta_x in (-1, 0, 1):
                    if delta_x == 0 and delta_y == 0:
                        continue
                    next_y, next_x = y + delta_y, x + delta_x
                    if 0 <= next_y < height and 0 <= next_x < width and remaining[next_y, next_x]:
                        remaining[next_y, next_x] = False
                        stack.append((next_y, next_x))
        found.append(np.asarray(indexes, dtype=np.int64))
    return found


def component_mask(shape: tuple[int, int], values: Iterable[np.ndarray]) -> np.ndarray:
    result = np.zeros(shape, dtype=bool)
    flat = result.reshape(-1)
    for value in values:
        flat[value] = True
    return result


def author(base: Image.Image, config: dict[str, object]) -> tuple[Image.Image, Image.Image]:
    rgba = np.asarray(base.convert("RGBA"), dtype=np.uint8)
    rgb = rgba[..., :3]
    alpha = rgba[..., 3]
    hue, saturation, value = rgb_to_hsv(rgb)
    red = rgb[..., 0].astype(np.float32)
    green = rgb[..., 1].astype(np.float32)
    blue = rgb[..., 2].astype(np.float32)
    visible = alpha > 12
    size = base.size

    # Actor ownership is geometry-only.  Companion/portal/prop colours do not
    # participate in this decision.
    matte_owner = polygons(size, config["matte_polygons"])
    matte_owner &= ~polygons(size, config.get("matte_exclude_polygons", ()))
    # Some recovery contacts have a soft floor shadow threaded between boots,
    # coat tails and knees.  These baked scanline spans are explicit negative
    # geometry authored for the source canvas; no source colour participates
    # when the batch is rebuilt.
    span_excludes = np.zeros_like(visible)
    for y, left, right in config.get("matte_exclude_spans", ()):
        if 0 <= y < size[1]:
            span_excludes[y, max(0, left):min(size[0], right + 1)] = True
    matte_owner &= ~span_excludes
    # Recoveries are explicit foreground actor silhouettes at occlusion
    # contacts (for example, hair crossing a portal/leaf).  They are applied
    # after negative companion/prop geometry by design.
    matte_owner |= polygons(size, config.get("matte_recover_polygons", ()))
    for y, left, right in config.get("matte_recover_spans", ()):
        if 0 <= y < size[1]:
            matte_owner[y, max(0, left):min(size[0], right + 1)] = True
    final_excludes = np.zeros_like(visible)
    for y, left, right in config.get("matte_final_exclude_spans", ()):
        if 0 <= y < size[1]:
            final_excludes[y, max(0, left):min(size[0], right + 1)] = True
    matte_owner &= ~final_excludes
    matte_membership = visible & matte_owner

    skin_owner = polygons(size, config["skin_polygons"])
    skin = (
        matte_membership & skin_owner
        & (hue >= 0.045) & (hue <= 0.098)
        & (saturation >= 0.37) & (saturation <= 0.72)
        & (value >= 0.52)
        & (red >= green * 1.13)
        & (green >= blue * 1.18)
    )

    hair_owner = polygons(size, [config["hair_polygon"]])
    hair_owner &= ~polygons(size, config.get("hair_exclude_polygons", ()))
    hair = (
        matte_membership & hair_owner
        & (hue >= 0.055) & (hue <= 0.16)
        & (saturation >= 0.25)
        & (value >= 0.055) & (value <= 0.62)
        & (red >= green * 1.02) & (green >= blue * 1.02)
    )

    # Leather gloves, belts and Shadow ornamentation share the same brown
    # ramp.  Hair ownership is therefore the connected crown/lock mass, not
    # every brown pixel inside a coarse head rectangle.
    hair_components = sorted(connected_components(hair), key=lambda item: item.size, reverse=True)
    if not hair_components:
        raise ValueError("authored hair component is empty")
    dominant = hair_components[0]
    dominant_rows, dominant_columns = np.divmod(dominant, hair.shape[1])
    selected_hair = [dominant]
    for item in hair_components[1:]:
        item_rows, item_columns = np.divmod(item, hair.shape[1])
        horizontal_gap = max(
            0,
            int(dominant_columns.min()) - int(item_columns.max()),
            int(item_columns.min()) - int(dominant_columns.max()),
        )
        vertical_gap = max(
            0,
            int(dominant_rows.min()) - int(item_rows.max()),
            int(item_rows.min()) - int(dominant_rows.max()),
        )
        if item.size >= 120 and horizontal_gap <= 28 and vertical_gap <= 28:
            selected_hair.append(item)
    hair = component_mask(hair.shape, selected_hair)

    eyes = np.zeros_like(visible)
    closed = bool(config.get("closed_eyes"))
    for box in (() if closed else config["eye_boxes"]):
        owner = rectangles(size, [box])
        eyes |= (
            matte_membership & owner
            & (value <= 0.34)
            & (saturation <= 0.92)
        )

    if not closed:
        brow_boxes = tuple((left - 14, top - 34, right + 14, top + 5) for left, top, right, _ in config["eye_boxes"])
        hair |= matte_membership & rectangles(size, brow_boxes) & (value <= 0.48) & ~eyes

    hair &= ~eyes
    skin &= ~(hair | eyes)
    packed = np.zeros_like(rgb)
    packed[..., 0] = np.where(skin, alpha, 0).astype(np.uint8)
    packed[..., 1] = np.where(hair, alpha, 0).astype(np.uint8)
    packed[..., 2] = np.where(eyes, alpha, 0).astype(np.uint8)
    matte = np.where(matte_membership, alpha, 0).astype(np.uint8)
    if np.any(packed.astype(np.uint16).sum(axis=2) > 255):
        raise ValueError("packed semantic channels overlap")
    if np.any(packed.max(axis=2) > matte):
        raise ValueError("semantic annotation escapes Traveller matte")
    return Image.fromarray(packed, "RGB"), Image.fromarray(matte, "L")


def write_png(path: Path, image: Image.Image, *, overwrite_owned: bool) -> None:
    if path.exists() and not overwrite_owned:
        raise FileExistsError(f"refusing to overwrite batch-owned target: {path.relative_to(ROOT)}")
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, "PNG", optimize=True)


def checkerboard(size: tuple[int, int], cell: int = 24) -> Image.Image:
    width, height = size
    yy, xx = np.indices((height, width))
    values = np.where(((xx // cell) + (yy // cell)) % 2, 224, 244).astype(np.uint8)
    return Image.fromarray(np.repeat(values[..., None], 3, axis=2), "RGB").convert("RGBA")


def overlay(base: Image.Image, matte: Image.Image) -> Image.Image:
    panel = checkerboard(base.size)
    panel.alpha_composite(base.convert("RGBA"))
    matte_data = np.asarray(matte.convert("L"), dtype=np.uint8)
    colour = np.zeros((*matte_data.shape, 4), dtype=np.uint8)
    colour[..., :3] = (0, 220, 255)
    colour[..., 3] = np.rint(matte_data.astype(np.float32) * 0.72).astype(np.uint8)
    panel.alpha_composite(Image.fromarray(colour, "RGBA"))
    return panel


def write_contact_sheets(
    assets: Sequence[dict[str, object]],
    results: dict[str, Validation],
) -> list[Path]:
    outputs: list[Path] = []
    PREVIEW_ROOT.mkdir(parents=True, exist_ok=True)
    for variant in ("male-v1", "female-f2-v1"):
        for capability in ("recovery-slug", "shadow"):
            rows = [item for item in assets if item["variant"] == variant and item["capability"] == capability]
            panel_width, panel_height, label_height = 256, 256, 30
            sheet = Image.new("RGB", (panel_width * 2, (panel_height + label_height) * len(rows)), (18, 20, 25))
            draw = ImageDraw.Draw(sheet)
            for row, asset in enumerate(rows):
                with Image.open(public_asset_path(REPO_ROOT, asset["baseRoute"])) as opened:
                    base = opened.convert("RGBA")
                with Image.open(safe_relative(ROOT, asset["matteFile"])) as opened:
                    matte = opened.convert("L")
                base_panel = checkerboard(base.size)
                base_panel.alpha_composite(base)
                matte_panel = overlay(base, matte)
                for column, panel in enumerate((base_panel, matte_panel)):
                    panel.thumbnail((panel_width, panel_height), Image.Resampling.LANCZOS)
                    x = column * panel_width + (panel_width - panel.width) // 2
                    y = row * (panel_height + label_height)
                    sheet.paste(panel.convert("RGB"), (x, y))
                state = "PASS" if results[str(asset["id"])].passed else "FAIL"
                draw.text((6, row * (panel_height + label_height) + panel_height + 4), f"{state}  {asset['frame']}", fill=(220, 245, 230) if state == "PASS" else (255, 100, 100))
            output = PREVIEW_ROOT / f"{variant}-{capability}-native-contact-sheet.png"
            sheet.save(output, "PNG", optimize=True)
            outputs.append(output)
    return outputs


