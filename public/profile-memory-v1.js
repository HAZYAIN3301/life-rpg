/* Satoru Profile Memory v1 (JARVIS-3-PLAN §2).
 *
 * Проблема, ради которой это существует: у бесплатной модели окно 8–32k токенов,
 * и год рефлексии туда не влезет никогда — ни при каком объёме хранилища.
 * Синхронизация телефон↔ноутбук при этом УЖЕ решена (данные лежат на сервере),
 * так что нерешена именно ёмкость.
 *
 * Решение — не архив, а поддерживаемая выжимка: ровно то, чем START-HERE.md
 * является для агента, который работает над этим проектом. ИИ её переписывает,
 * человек читает и правит, размер жёстко ограничен.
 *
 * ⚠️ Ключевой принцип, унаследованный от DISCIPLINE-BOUNDARIES-PLAN и его нельзя
 * терять: паттерны считаются ЛОКАЛЬНО, ИИ только проговаривает. Сюда приезжают
 * уже посчитанные факты, и модели прямо запрещено выводить новые закономерности.
 * Слабая модель плохо выводит и вполне прилично переформулирует — вся тяжёлая
 * работа остаётся бесплатной и локальной.
 *
 * Модуль намеренно без DOM и без сети: чистые функции, тестируемые из Node.
 */
(function exposeProfileMemory(root, factory) {
  const api = factory(root);
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.ProfileMemoryV1 = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function buildProfileMemory() {
  'use strict';

  const VERSION = '1.0.0';

  // Бюджет в СИМВОЛАХ, а не токенах: токенизатор в браузере недоступен, а символы
  // считаются точно и бесплатно. 3000 символов кириллицы ≈ 1200–2000 токенов —
  // помещается в окно 8k вместе с недавними рефлексиями, вопросом и системной частью.
  // Это потолок, а не цель: короткий профиль лучше длинного.
  const MAX_CHARS = 3000;

  // Разделы профиля. Порядок = приоритет при обрезке: то, что ниже, теряется первым,
  // поэтому «кто это» стоит выше «открытых ниток».
  const SECTIONS = Object.freeze([
    'Кто это',            // сферы, цели, ограничения, язык
    'Устойчивые паттерны', // из локального детектора, НЕ догадки ИИ
    'Что уже пробовали',   // что сработало, что нет
    'Сейчас',              // текущий сезон/фокус
    'Открытые нитки',      // к чему обещали вернуться
  ]);

  /** Убирает обёртки, которыми модели любят украшать ответ: код-фенсы и преамбулы. */
  function normalize(raw) {
    let s = String(raw == null ? '' : raw).trim();
    const fence = /^```[a-z]*\s*\n([\s\S]*?)\n?```$/i.exec(s);
    if (fence) s = fence[1].trim();
    // «Вот обновлённый профиль:» и подобное — только если это отдельная первая строка
    // и за ней есть ещё текст. Иначе рискуем срезать содержательное начало.
    const lines = s.split('\n');
    if (lines.length > 1 && /^[^\n]{0,80}:$/.test(lines[0]) && !lines[0].startsWith('#')) {
      s = lines.slice(1).join('\n').trim();
    }
    return s.replace(/\n{3,}/g, '\n\n');
  }

  /**
   * Жёсткая обрезка до бюджета. Режем ПО ГРАНИЦЕ СТРОКИ: оборванная на полуслове
   * строка выглядит как баг и тратит доверие, которое эта фича как раз и строит.
   * Идемпотентна — повторный вызов ничего не меняет.
   */
  function enforceBudget(text, max) {
    const lim = Number(max) > 0 ? Number(max) : MAX_CHARS;
    const s = String(text == null ? '' : text).trim();
    if (s.length <= lim) return s;
    const cut = s.slice(0, lim);
    const lastBreak = cut.lastIndexOf('\n');
    // Если первая же строка длиннее лимита, границы нет — режем по словам.
    if (lastBreak <= 0) {
      const byWord = cut.lastIndexOf(' ');
      return (byWord > 0 ? cut.slice(0, byWord) : cut).trim();
    }
    return cut.slice(0, lastBreak).trim();
  }

  /** Профиль пуст? (пробелы не считаются содержимым) */
  function isEmpty(profile) {
    return !profile || !String(profile.text || '').trim();
  }

  /**
   * Промпт на обновление профиля. Факты приходят уже посчитанными — модель их
   * компонует и сжимает, но не выводит новых.
   */
  function buildPrompt(facts, currentText, max) {
    const lim = Number(max) > 0 ? Number(max) : MAX_CHARS;
    const f = facts || {};
    const prev = String(currentText || '').trim();
    const block = (title, val) => (val && String(val).trim() ? `\n${title}:\n${String(val).trim()}` : '');

    return `Ты ведёшь краткий профиль человека в приложении Satoru — как досье, которое читает секретарь перед разговором, чтобы не переспрашивать одно и то же.

ЖЁСТКИЕ ПРАВИЛА:
1. Максимум ${lim} символов. Это потолок, а не цель. Если не влезает — ВЫБРОСЬ менее важное, не сокращай всё до неразборчивости. Профиль, который только растёт, через полгода станет бесполезен.
2. Ничего не выдумывай и НЕ ВЫВОДИ новых закономерностей. Паттерны ниже посчитаны программой по реальным данным — твоя работа переформулировать и сохранить, а не диагностировать.
3. Пиши на языке человека (${f.lang || 'ru'}), от третьего лица, короткими утверждениями. Без воды, без похвалы, без советов.
4. Сохрани из прошлой версии то, что всё ещё верно — особенно «что уже пробовали» и «открытые нитки». Это память, а не отчёт за неделю: если выбросишь, оно потеряется навсегда.
5. Верни ТОЛЬКО текст профиля. Без преамбулы, без код-блоков.

СТРУКТУРА (короткие разделы, пропускай пустые):
${SECTIONS.map((s) => `## ${s}`).join('\n')}
${prev ? `\nПРОШЛАЯ ВЕРСИЯ ПРОФИЛЯ (обнови её, а не пиши с нуля):\n${prev}` : '\nПрошлой версии нет — составь первую.'}

СВЕЖИЕ ФАКТЫ (посчитаны программой, не выдумывай другие):${block('Сферы', f.spheres)}${block('Цели', f.goals)}${block('Найденный паттерн', f.pattern)}${block('Состояние', f.state)}${block('Его собственные слова за последнее время', f.reflections)}`;
  }

  /** Метаданные для UI: сколько занято от бюджета. */
  function usage(profile, max) {
    const lim = Number(max) > 0 ? Number(max) : MAX_CHARS;
    const n = String((profile && profile.text) || '').length;
    return { chars: n, max: lim, pct: Math.min(100, Math.round((n / lim) * 100)) };
  }

  return { VERSION, MAX_CHARS, SECTIONS, normalize, enforceBudget, isEmpty, buildPrompt, usage };
});
