#!/bin/sh
# Собирает самодостаточную копию визуального листа: картинки уменьшаются до размера показа
# и вшиваются в HTML как data: URI. Нужно, чтобы файл можно было переслать или открыть
# с телефона — версия с относительными путями работает только рядом с public/art.
#
#   sh build-portable.sh [выходной-файл]
#
# Оригиналы не изменяются. Уменьшенные копии живут во временной папке и удаляются.
set -e
OUT="${1:-visual-sheet-portable.html}"
python3 "$(dirname "$0")/build-portable.py" "$OUT"
