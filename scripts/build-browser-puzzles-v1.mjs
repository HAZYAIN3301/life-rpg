// Builds extensions/satoru-attention/puzzles.js — the bundled chess puzzles for the doomscroll
// boundary (owner decision 26.09: solve a hard puzzle every N minutes). Source: the Lichess puzzle
// database, CC0 (https://database.lichess.org/#puzzles). Usage:
//   curl -s https://database.lichess.org/lichess_db_puzzle.csv.zst | zstd -dc | head -n 300000 > sample.csv
//   node scripts/build-browser-puzzles-v1.mjs sample.csv
// The CSV is not committed; its SHA-256 and the selection rules are recorded in puzzles.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const input = process.argv[2];
if (!input) throw new Error('pass a Lichess puzzle CSV');
const raw = readFileSync(input);
const lines = raw.toString('utf8').split('\n');
const header = lines[0].split(',');
const col = (name) => { const i = header.indexOf(name); if (i < 0) throw new Error(`missing column ${name}`); return i; };
const C = { id: col('PuzzleId'), fen: col('FEN'), moves: col('Moves'), rating: col('Rating'), dev: col('RatingDeviation'),
  pop: col('Popularity'), plays: col('NbPlays'), themes: col('Themes') };
const TIERS = { normal: [1500, 1799], hard: [1800, 2099], brutal: [2100, 2499] };
const PER_TIER = 800;
const FEN = /^([pnbrqkPNBRQK1-8]+\/){7}[pnbrqkPNBRQK1-8]+ [wb] (-|[KQkq]+) (-|[a-h][36]) \d+ \d+$/;
const UCI = /^[a-h][1-8][a-h][1-8][qrbn]?$/;
const picked = { normal: [], hard: [], brutal: [] };
// 07.10: the owner could not tell what a puzzle wanted ("не шах и не мат — в чём цель?"). Lichess
// themes say it: mateInN, crushing (decisive gain), advantage, equality (save the game). The goal is
// shown before the first move; the tactical motif only after the puzzle ends (it would be a hint).
const MOTIFS = ['fork', 'pin', 'skewer', 'discoveredAttack', 'doubleCheck', 'hangingPiece', 'trappedPiece', 'deflection', 'attraction',
  'interference', 'clearance', 'capturingDefender', 'xRayAttack', 'sacrifice', 'intermezzo', 'quietMove', 'defensiveMove', 'promotion',
  'backRankMate', 'smotheredMate', 'kingsideAttack', 'exposedKing'];
function goalOf(themes) {
  const mate = themes.find((t) => /^mateIn[1-5]$/.test(t));
  if (mate) return `m${mate.slice(6)}`;
  return themes.includes('crushing') ? 'win' : themes.includes('advantage') ? 'adv' : themes.includes('equality') ? 'eq' : '';
}
function motifOf(themes) { return MOTIFS.find((m) => themes.includes(m)) || ''; }
for (const line of lines.slice(1)) {
  if (!line) continue;
  const f = line.split(',');
  const rating = Number(f[C.rating]); const moves = f[C.moves].split(' ');
  if (!FEN.test(f[C.fen]) || !moves.every((m) => UCI.test(m))) continue;
  // Lichess format: moves[0] is the opponent's move, then the player and opponent alternate.
  // Keep 2–4 player moves: moves.length is even, 4..8.
  if (moves.length < 4 || moves.length > 8 || moves.length % 2) continue;
  if (Number(f[C.pop]) < 85 || Number(f[C.plays]) < 2000 || Number(f[C.dev]) > 80) continue;
  const tier = Object.keys(TIERS).find((key) => rating >= TIERS[key][0] && rating <= TIERS[key][1]);
  if (!tier || picked[tier].length >= PER_TIER) continue;
  const themes = f[C.themes].split(' ');
  picked[tier].push([f[C.id], f[C.fen], f[C.moves], rating, goalOf(themes), motifOf(themes)]);
}
for (const [tier, list] of Object.entries(picked)) if (list.length < PER_TIER) throw new Error(`${tier}: only ${list.length}`);
const data = { source: 'Lichess puzzle database', url: 'https://database.lichess.org/#puzzles', license: 'CC0-1.0',
  sha256: createHash('sha256').update(raw).digest('hex'), selection: { tiers: TIERS, perTier: PER_TIER,
    minPopularity: 85, minPlays: 2000, maxRatingDeviation: 80, playerMoves: '2-4' },
  goals: { m2: 'mateIn2', m3: 'mateIn3', m4: 'mateIn4', m5: 'mateIn5', win: 'crushing', adv: 'advantage', eq: 'equality' }, puzzles: picked };
writeFileSync(join(root, 'extensions/satoru-attention/puzzles.js'), `/* Generated by scripts/build-browser-puzzles-v1.mjs — chess puzzles from the Lichess puzzle
 * database (CC0-1.0, https://database.lichess.org/#puzzles). Row: [id, fen, "uci moves", rating, goal, motif].
 * Contract: PUZZLES-CONTRACT.md. */
(function exposePuzzles(root) {
  const api = Object.freeze(${JSON.stringify(data)});
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.SatoruPuzzles = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`);
console.log(JSON.stringify(Object.fromEntries(Object.entries(picked).map(([k, v]) => [k, v.length]))));
