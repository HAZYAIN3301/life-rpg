#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const args = Object.fromEntries(process.argv.slice(2).map((entry) => {
  const [key, ...rest] = entry.replace(/^--/, '').split('=');
  return [key, rest.join('=')];
}));
const servicesRoot = path.resolve(args.services || '/private/tmp/nextdns-services-v209');
const bypassRoot = path.resolve(args.bypass || '/private/tmp/nextdns-bypass-v209');
const piracyRoot = path.resolve(args.piracy || '/private/tmp/nextdns-piracy-v209');
const output = path.join(root, 'extensions', 'satoru-attention', 'protection-catalog.js');

function lines(file) {
  return fs.readFileSync(file, 'utf8').split(/\r?\n/)
    .map((line) => line.replace(/#.*/, '').trim().toLowerCase())
    .filter((line) => /^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$/.test(line) && line.includes('.'));
}

function service(names) {
  return names.flatMap((name) => lines(path.join(servicesRoot, 'services', name)));
}

function allLists(folder, excluded = new Set(['LICENSE'])) {
  return fs.readdirSync(folder).sort().flatMap((name) => {
    const file = path.join(folder, name);
    return excluded.has(name) || !fs.statSync(file).isFile() ? [] : lines(file);
  });
}

function unique(values) {
  return [...new Set(values)].sort();
}

const manual = {
  adult: [
    'pornhub.com', 'xvideos.com', 'xnxx.com', 'xhamster.com', 'redtube.com', 'youporn.com',
    'onlyfans.com', 'fansly.com', 'chaturbate.com', 'stripchat.com', 'livejasmin.com',
  ],
  gambling: [
    '1xbet.com', 'bet365.com', 'betway.com', 'bwin.com', 'draftkings.com', 'fanduel.com',
    'pokerstars.com', 'stake.com', 'unibet.com', 'williamhill.com',
  ],
  dating: ['badoo.com', 'bumble.com', 'grindr.com', 'hinge.co', 'match.com', 'okcupid.com'],
};

const catalog = {
  social: unique(service(['facebook', 'instagram', 'twitter', 'tiktok', 'reddit', 'vk', 'snapchat', 'tumblr', 'pinterest', 'mastodon', 'bereal', '9gag', 'imgur'])),
  video: unique(service(['youtube', 'netflix', 'twitch', 'hbomax', 'vimeo', 'dailymotion', 'primevideo', 'hulu'])),
  gaming: unique(service(['steam', 'roblox', 'xboxlive', 'playstation-network', 'leagueoflegends', 'blizzard', 'minecraft'])),
  dating: unique(service(['tinder']).concat(manual.dating)),
  gambling: unique(manual.gambling),
  adult: unique(manual.adult),
  piracy: unique(allLists(piracyRoot)),
  bypass: unique(allLists(bypassRoot)),
};

const source = `/* Generated by scripts/build-browser-protection-catalog-v210.mjs.
 * Upstream domain metadata: NextDNS services, dns-bypass-methods and piracy-blocklists (MIT).
 * Exact revisions and attribution are recorded in THIRD-PARTY-NOTICES.md.
 */
(function exposeProtectionCatalog(root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.SatoruProtectionCatalog = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function buildProtectionCatalog() {
  'use strict';
  const CATALOG = ${JSON.stringify(catalog, null, 2)};
  for (const key of Object.keys(CATALOG)) Object.freeze(CATALOG[key]);
  return Object.freeze(CATALOG);
});
`;

fs.writeFileSync(output, source);
const counts = Object.fromEntries(Object.entries(catalog).map(([key, value]) => [key, value.length]));
process.stdout.write(`${JSON.stringify({ output, counts, total: Object.values(counts).reduce((a, b) => a + b, 0) }, null, 2)}\n`);
