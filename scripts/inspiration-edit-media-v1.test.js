'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const E=require('../public/inspiration-edit-media-v1.js');
const {createSigner,fromPost}=require('../server-inspiration-apify-v1.js');
const P=require('../public/inspiration-profile-v1.js'),R=require('../public/inspiration-supply-runtime-v1.js');
const Owner=require('../server-inspiration-profile-v1.js'),Policy=require('../public/inspiration-supply-policy-v1.js');
const at='2026-10-29T09:00:00.000Z',day=at.slice(0,10);
const post=(id='7111111111111111111',text='Gojo anime edit #jjk #animeedit')=>({id,text,webVideoUrl:`https://www.tiktok.com/@sample/video/${id}`,authorMeta:{name:'sample'},videoMeta:{duration:21},createTimeISO:'2026-10-28T08:00:00.000Z'});
const profile=(extra={})=>P.configure({interests:[{id:'anime',label:'Anime'}],formats:['edit'],...extra});
const signer=createSigner(()=> 'only-a-synthetic-test-secret');
const candidate=(id)=>signer.sign(fromPost(post(id),['anime'],at),'qa');
test('public edit metadata must show both the requested topic and edit intent; no guessed media files',()=>{
 const item=fromPost(post(),['anime','fitness'],at);assert.deepEqual(item.interestIds,['anime']);
 assert.equal(item.title.ru,'Gojo anime edit');assert.ok(item.tags.includes('animeedit'));
 assert.equal(item.rights.kind,'linked-public');assert.equal(item.rights.downloadAllowed,false);
 assert.equal(item.imageUrl,'');assert.equal(item.videoUrl,undefined);assert.equal(item.available,'unknown');
 assert.equal(fromPost(post(undefined,'Anime news from today'),['anime'],at),null);
 assert.equal(fromPost(post(undefined,'Gym motivation edit'),['anime'],at),null);
 assert.equal(fromPost({...post(),id:'7222222222222222222'},['anime'],at),null);
 assert.equal(fromPost({...post(),videoMeta:{duration:181}},['anime'],at),null);
 assert.equal(fromPost({...post(),isSlideshow:true},['anime'],at),null);
});
test('signed private recommendation is account-bound and cannot grant a shared catalogue licence',()=>{
 const item=candidate();assert.ok(E.normalize(item));assert.equal(signer.verify(item,'qa'),true);
 assert.equal(signer.verify(item,'another-account'),false);
 assert.equal(signer.verify({...item,title:{...item.title,ru:'forged'}},'qa'),false);
 assert.equal(Owner.cleanFind(item),null);
 assert.ok(Owner.cleanFind(item,{verifyEdit:x=>signer.verify(x,'qa')}));
 assert.equal(Owner.cleanFind(item,{verifyEdit:x=>signer.verify(x,'other')}),null);
 assert.equal(Policy.admit([item],{now:at}).items.length,0);
});
test('private pool reuses fixed-day selection, cooldown, reference exclusion and feedback',()=>{
 const a=candidate(),b=candidate('7222222222222222222'),c=candidate('7333333333333333333');
 const options={profile:profile(),day,now:at,candidates:[a,b,c],locale:'ru',ctx:{maxSharePerSource:1}};
 const chosen=R.ensureDigest(options);assert.equal(chosen.items.length,3);
 const duplicate=R.ensureDigest({...options,candidates:[a,a,b,c]});assert.equal(new Set(duplicate.items.map(i=>i.id)).size,3);assert.equal(duplicate.poolRows.length,3);
 assert.ok(chosen.items.every(i=>i.personalMedia&&i.mediaPolicy==='iframe'));
 const recorded=P.recordShown(chosen.profile,day);
 const tomorrow=R.ensureDigest({...options,profile:recorded,day:'2026-10-30',now:'2026-10-30T09:00:00.000Z'});
 assert.equal(tomorrow.items.length,0);
 const fixed=R.ensureDigest({...options,profile:recorded,candidates:[a]});assert.deepEqual(fixed.profile.digest,recorded.digest);assert.equal(fixed.items.length,1);
 const ref=R.ensureDigest({...options,profile:profile({videoReferences:[{url:a.delivery.sourceUrl}]})});assert.equal(ref.items.length,2);
 const rejected=P.recordFeedback(profile(),E.toRow(a),'not_for_me',day,'');
 assert.equal(R.ensureDigest({...options,profile:rejected}).items.length,2);
 const saved=R.resolveSaved({id:'saved',catalogId:a.id,url:a.delivery.sourceUrl,title:'My edit',format:'edit'},[]);
 assert.equal(saved.supplyUnavailable,false);assert.equal(saved.personalMedia,true);assert.ok(saved.embedUrl);
 const currentSaved=R.resolveSaved({id:'saved',catalogId:a.id,url:a.delivery.sourceUrl,title:'My edit',format:'edit'},[E.toRow(a)]);
 assert.equal(currentSaved.catalogItem,null,'Saved recommendations use the personal saved-card layout once');
 assert.ok(require('../public/inspiration-tiktok-frame-v1.js').personalSource(currentSaved),'Saving a daily edit must preserve internal playback');
 assert.equal(R.resolveSaved({id:'saved',catalogId:'unlicensed',url:a.delivery.sourceUrl},[]).supplyUnavailable,true);
});
